/**
 * Resolves the appropriate Leaflet map zoom level for a place string based on geographic scope.
 * 
 * @param {string} place - Place name string
 * @returns {number} Leaflet zoom level (e.g. 4 for country, 8 for state, 12 for city)
 * 
 * @example
 * getZoomForLocation('India');
 * // => 5
 * 
 * @example
 * getZoomForLocation('Chicago');
 * // => 12
 */
const getZoomForLocation = (place) => {
    if (!place) return 10;
    const norm = place.toLowerCase().trim();
    if (LOCATION_ZOOM_LEVELS[norm]) return LOCATION_ZOOM_LEVELS[norm];
    for (const [k, v] of Object.entries(LOCATION_ZOOM_LEVELS)) {
        if (norm.includes(k) || k.includes(norm)) return v;
    }
    return 14;
};

/**
 * Pans and zooms a Leaflet map instance to a named location.
 *
 * Looks up existing map marker coordinates first, falling back to pre-geocoded coordinates.
 *
 * @param {Object} mapInstance - Leaflet map instance
 * @param {Array<Object>} markers - Rendered map markers
 * @param {string} place - Target location name
 * @param {number} [duration=0.8] - Animation duration in seconds
 * 
 * @example
 * flyMapToPlace(mapInstance, markers, 'Kochi');
 * 
 * @example
 * flyMapToPlace(mapInstance, markers, 'San Jose', 1.2);
 */
function flyMapToPlace(mapInstance, markers, place, duration = 0.8) {
    if (!mapInstance || !place) return;
    const zoom = getZoomForLocation(place);
    const norm = place.toLowerCase().trim();
    const item = markers ? markers.find(m => m.place && m.place.toLowerCase().trim() === norm) : null;
    const coords = item ? item.coords : resolveLocationCoords(place);
    if (coords) {
        mapInstance.flyTo(coords, zoom, { duration });
    }
}

/**
 * Groups living/known people in the family tree by valid location.
 *
 * Excludes ghosts, unknown placeholders, and invalid location names.
 * Returns groups ordered descending by resident count.
 *
 * @param {FamilyTree} tree - Active family tree model
 * @returns {Array<{place: string, people: Array<Person>, count: number}>} Grouped locations
 * 
 * @example
 * computePlaceGroups(tree);
 * // => [{ place: 'Kochi', people: [...], count: 12 }, { place: 'Thrissur', people: [...], count: 8 }]
 * 
 * @example
 * computePlaceGroups(null);
 * // => []
 */
function computePlaceGroups(tree) {
    if (!tree || !tree.all) return [];
    const groups = {};
    tree.all.forEach(p => {
        if (p.place && p.place.trim() && !p.isGhost && !p._isUnknown) {
            const place = p.place.trim();
            if (!FamilyTreeBuilder.isInvalidLocation(place)) {
                if (!groups[place]) groups[place] = [];
                groups[place].push(p);
            }
        }
    });
    return Object.entries(groups)
        .map(([place, people]) => ({ place, people, count: people.length }))
        .sort((a, b) => b.count - a.count);
}

/**
 * Retrieves or initializes an accumulator node in the location hierarchy tree.
 *
 * @param {Object} parentMap - Parent dictionary container.
 * @param {string} key - Node identifier key.
 * @param {Function} factory - Constructor callback for creating initial node state.
 * @returns {Object} Node record.
 *
 * @example
 * const node = _getOrCreateHierarchyNode(countryMap, 'India', () => ({ name: 'India', flag: '📍', count: 0, locations: [], states: {} }));
 * // => { name: 'India', flag: '📍', count: 0, locations: [], states: {} }
 * 
 * @example
 * _getOrCreateHierarchyNode(cNode.states, 'Kerala', () => ({ name: 'Kerala', count: 0, locations: [], districts: {} }));
 * // => { name: 'Kerala', count: 0, locations: [], districts: {} }
 */
function _getOrCreateHierarchyNode(parentMap, key, factory) {
    if (!parentMap[key]) {
        parentMap[key] = factory();
    }
    return parentMap[key];
}

/**
 * Inserts a location group into a state hierarchy node or its nested district node.
 *
 * @param {Object} cNode - Parent country hierarchy node
 * @param {string} state - State name
 * @param {string|null} district - Optional district name
 * @param {Object} group - Place group record with count and place string
 *
 * @example
 * _insertStateLocation(cNode, 'Kerala', 'Thrissur', { place: 'Ollur', count: 5 });
 *
 * @example
 * _insertStateLocation(cNode, 'California', null, { place: 'California', count: 2 });
 */
function _insertStateLocation(cNode, state, district, group) {
    const sNode = _getOrCreateHierarchyNode(cNode.states, state, () => ({
        name: state, count: 0, locations: [], districts: {}
    }));
    sNode.count += group.count;

    if (!district) {
        sNode.locations.push(group);
        return;
    }

    const dNode = _getOrCreateHierarchyNode(sNode.districts, district, () => ({
        name: district, count: 0, locations: []
    }));
    dNode.count += group.count;
    dNode.locations.push(group);
}

/**
 * Inserts a place group record into the country -> state -> district accumulator map.
 * 
 * @param {Object} countryMap - Country accumulator map
 * @param {Object} group - Place group record
 * 
 * @example
 * _insertLocationIntoHierarchy(map, { place: 'Ollur, Thrissur, Kerala, India', count: 5 });
 * 
 * @example
 * _insertLocationIntoHierarchy(map, { place: 'London, United Kingdom', count: 3 });
 */
function _insertLocationIntoHierarchy(countryMap, group) {
    const { country, state, district } = resolvePlaceHierarchy(group.place);
    const flag = COUNTRY_FLAGS[country] || '📍';

    const cNode = _getOrCreateHierarchyNode(countryMap, country, () => ({
        name: country, flag, count: 0, locations: [], states: {}
    }));
    cNode.count += group.count;

    if (!state) {
        cNode.locations.push(group);
        return;
    }

    _insertStateLocation(cNode, state, district, group);
}

/**
 * Formats and sorts a district hierarchy node and its contained locations by resident count.
 * 
 * @param {Object} d - District record containing name, count, and locations
 * @param {Function} sortFn - Count comparator function
 * @returns {Object} Formatted district node
 * 
 * @example
 *   _formatHierarchyDistrictNode(dist, (a, b) => b.count - a.count);
 * 
 * @example
 *   _formatHierarchyDistrictNode({ name: 'Thrissur', count: 5, locations: [] }, (a, b) => b.count - a.count);
 */
function _formatHierarchyDistrictNode(d, sortFn) {
    return {
        ...d,
        locations: d.locations.sort(sortFn)
    };
}

/**
 * Formats and sorts a state hierarchy node, its contained districts, and direct locations by resident count.
 * 
 * @param {Object} s - State record containing name, count, locations, and districts map
 * @param {Function} sortFn - Count comparator function
 * @returns {Object} Formatted state node
 * 
 * @example
 *   _formatHierarchyStateNode(state, (a, b) => b.count - a.count);
 * 
 * @example
 *   _formatHierarchyStateNode({ name: 'Kerala', count: 10, locations: [], districts: {} }, (a, b) => b.count - a.count);
 */
function _formatHierarchyStateNode(s, sortFn) {
    return {
        ...s,
        locations: s.locations.sort(sortFn),
        districts: Object.values(s.districts)
            .sort(sortFn)
            .map(d => _formatHierarchyDistrictNode(d, sortFn))
    };
}

/**
 * Converts country accumulator map into a sorted nested array sorted by resident count descending.
 * 
 * @param {Object} countryMap - Populated country accumulator map
 * @returns {Array<Object>} Sorted nested hierarchy array
 * 
 * @example
 *   _formatLocationHierarchy(map)
 *   // => [{ name: 'India', count: 10, states: [...] }]
 * 
 * @example
 *   _formatLocationHierarchy({})
 *   // => []
 */
function _formatLocationHierarchy(countryMap) {
    const sortByCount = (a, b) => b.count - a.count;
    return Object.values(countryMap)
        .sort(sortByCount)
        .map(c => ({
            ...c,
            locations: c.locations.sort(sortByCount),
            states: Object.values(c.states)
                .sort(sortByCount)
                .map(s => _formatHierarchyStateNode(s, sortByCount))
        }));
}

/**
 * Builds a hierarchical tree (country -> state -> district -> locations) from place groups.
 *
 * Resolves each place against LOCATION_GEO_HIERARCHY and attaches corresponding country flags.
 * Groups are filtered by an optional search query string.
 *
 * @param {Array<Object>} placeGroups - Flat list of place groups
 * @param {string} [searchQuery=''] - Optional filter substring
 * @returns {Array<Object>} Nested hierarchy of countries, states, and districts
 * 
 * @example
 * buildLocationHierarchy(placeGroups, 'kerala');
 * // => [{ name: 'India', count: 12, states: [...] }]
 * 
 * @example
 * buildLocationHierarchy([], '');
 * // => []
 */
function buildLocationHierarchy(placeGroups, searchQuery = '') {
    const countryMap = {};
    const q = (searchQuery || '').toLowerCase().trim();

    placeGroups.forEach(group => {
        if (q && !group.place.toLowerCase().includes(q)) return;
        _insertLocationIntoHierarchy(countryMap, group);
    });

    return _formatLocationHierarchy(countryMap);
}

/**
 * Generic helper to group people by a specified text attribute (optionally splitting multiple tokens),
 * filtering against a search query, and sorting descending by member count.
 *
 * @param {FamilyTree} tree - The family tree model.
 * @param {string} attrName - Profile property name (e.g. 'job', 'family').
 * @param {string} [searchQuery=''] - Optional substring filter.
 * @param {boolean} [splitTokens=false] - Whether comma-separated values should be split into individual tokens.
 * @returns {Array<{ [attrName]: string, people: Array<Person>, count: number }>} Grouped and sorted list.
 *
 * @example
 * groupPeopleByAttribute(tree, 'family', 'chalissery', false);
 * // => [{ family: 'Chalissery', people: [...], count: 18 }]
 * 
 * @example
 * groupPeopleByAttribute(tree, 'job', 'engineer', true);
 * // => [{ job: 'Engineer', people: [...], count: 5 }]
 */
function groupPeopleByAttribute(tree, attrName, searchQuery = '', splitTokens = false) {
    if (!tree || !tree.all) return [];
    const groups = {};
    tree.all.forEach(p => {
        const val = p[attrName];
        if (val && typeof val === 'string' && val.trim() && !p.isGhost && !p._isUnknown) {
            const tokens = splitTokens ? parseCommaDelimitedTokens(val) : [val.trim()];
            tokens.forEach(tok => {
                if (!groups[tok]) groups[tok] = [];
                groups[tok].push(p);
            });
        }
    });
    const q = (searchQuery || '').toLowerCase().trim();
    return Object.entries(groups)
        .map(([key, people]) => ({ [attrName]: key, people, count: people.length }))
        .filter(g => !q || g[attrName].toLowerCase().includes(q))
        .sort((a, b) => b.count - a.count);
}

/**
 * Groups people by career/job titles parsed from comma-separated tokens.
 *
 * @param {FamilyTree} tree - Active family tree model
 * @param {string} [searchQuery=''] - Optional filter substring
 * @returns {Array<{job: string, people: Array<Person>, count: number}>} Filtered and sorted jobs
 * 
 * @example
 * computeJobGroups(tree, 'doctor');
 * // => [{ job: 'Doctor', people: [...], count: 3 }]
 * 
 * @example
 * computeJobGroups(tree, '');
 * // => [{ job: 'Engineer', people: [...], count: 6 }, ...]
 */
function computeJobGroups(tree, searchQuery = '') {
    return groupPeopleByAttribute(tree, 'job', searchQuery, true);
}

/**
 * Groups people by family name / house name.
 *
 * @param {FamilyTree} tree - Active family tree model
 * @param {string} [searchQuery=''] - Optional filter substring
 * @returns {Array<{family: string, people: Array<Person>, count: number}>} Filtered and sorted families
 * 
 * @example
 * computeFamilyGroups(tree, 'chalissery');
 * // => [{ family: 'Chalissery', people: [...], count: 18 }]
 * 
 * @example
 * computeFamilyGroups(tree, '');
 * // => [{ family: 'Maramattathil', people: [...], count: 24 }, ...]
 */
function computeFamilyGroups(tree, searchQuery = '') {
    return groupPeopleByAttribute(tree, 'family', searchQuery, false);
}

