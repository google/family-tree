/**
 * Cleans and formats a raw place name for display in the directory selector,
 * stripping redundant state/district/country parent suffixes.
 *
 * @param {string} place - Raw place name
 * @param {string|null} [parentState=null] - Parent state name
 * @param {string|null} [parentDistrict=null] - Parent district name
 * @param {string|null} [parentCountry=null] - Parent country name
 * @returns {string} Cleaned place display name
 *
 * @example
 * cleanLocationDisplayName('Kochi, Kerala', 'Kerala')
 * // => 'Kochi'
 *
 * @example
 * cleanLocationDisplayName('Seattle, WA')
 * // => 'Seattle'
 */
function cleanLocationDisplayName(place, parentState = null, parentDistrict = null, parentCountry = null) {
    if (!place || FamilyTreeBuilder.isInvalidLocation(place)) return '';
    const p = place.trim();
    const norm = p.toLowerCase();
    
    // Explicit known cleanups
    if (norm.includes('seattle')) return 'Seattle';
    if (norm.includes('naples')) return 'Naples';
    
    const parts = p.split(',').map(s => s.trim()).filter(Boolean);
    return parts.length > 0 ? parts[0] : p;
}

/**
 * Checks if two location strings match by exact equality, comma-separated token inclusion, or substring inclusion.
 *
 * @param {?string} itemPlace - Place string from person or location node
 * @param {?string} filterPlace - Filter or query place string
 * @returns {boolean} True if the places are considered matching
 *
 * @example
 * isPlaceMatch("Kochi, Ernakulam", "Kochi");
 * // => true
 *
 * @example
 * isPlaceMatch("New York", "London");
 * // => false
 */
function isPlaceMatch(itemPlace, filterPlace) {
    if (!itemPlace || !filterPlace) return false;
    const i = itemPlace.toLowerCase().trim();
    const f = filterPlace.toLowerCase().trim();
    if (i === f) return true;
    const iParts = i.split(',').map(s => s.trim());
    if (iParts.includes(f)) return true;
    const fParts = f.split(',').map(s => s.trim());
    if (fParts.includes(i)) return true;
    return i.includes(f) || f.includes(i);
}

/**
 * Resolves the active directory tab ('place' | 'job' | 'family') from activeFilter or fallback tab.
 *
 * @param {?{filterType?: string, tab?: string}} activeFilter - Current filter state
 * @param {string} [fallbackTab='place'] - Default fallback tab
 * @returns {'place'|'job'|'family'} Resolved tab identifier
 *
 * @example
 * resolveActiveDirectoryTab({ filterType: 'job', value: 'Doctor' });
 * // => 'job'
 *
 * @example
 * resolveActiveDirectoryTab(null, 'place');
 * // => 'place'
 */
function resolveActiveDirectoryTab(activeFilter, fallbackTab = 'place') {
    if (activeFilter?.filterType && ['place', 'job', 'family'].includes(activeFilter.filterType)) {
        return activeFilter.filterType;
    }
    if (activeFilter?.filterType === 'directory' && activeFilter.tab) {
        return activeFilter.tab;
    }
    return fallbackTab || 'place';
}

/**
 * Uncollapses hierarchical location ancestor keys (country, state, district)
 * corresponding to an active place or matching place groups.
 *
 * @param {Object<string, boolean>} collapsedNodes - Map of collapsed node keys
 * @param {string|null} activePlaceName - Name of currently active place filter
 * @param {Array<{place: string}>} placeGroups - Grouped place records
 * @param {Function} [matcher=isPlaceMatch] - Matcher function between two place strings
 * @returns {Object<string, boolean>} Updated collapsed nodes map
 *
 * @example
 * uncollapseLocationHierarchy({ 'India': true, 'India/Kerala': true }, 'Kochi', [{ place: 'Kochi' }])
 * // => {} (uncollapses 'India' and 'India/Kerala')
 *
 * @example
 * uncollapseLocationHierarchy({ 'India': true }, null, [])
 * // => { 'India': true }
 */
function uncollapseLocationHierarchy(collapsedNodes, activePlaceName, placeGroups, matcher = isPlaceMatch) {
    if (!activePlaceName) return collapsedNodes;
    const next = { ...collapsedNodes };
    const directH = resolvePlaceHierarchy(activePlaceName);
    if (directH.country) delete next[directH.country];
    if (directH.country && directH.state) delete next[`${directH.country}/${directH.state}`];
    if (directH.country && directH.state && directH.district) delete next[`${directH.country}/${directH.state}/${directH.district}`];

    placeGroups.forEach(group => {
        if (matcher(group.place, activePlaceName)) {
            const h = resolvePlaceHierarchy(group.place);
            if (h.country) delete next[h.country];
            if (h.country && h.state) delete next[`${h.country}/${h.state}`];
            if (h.country && h.state && h.district) delete next[`${h.country}/${h.state}/${h.district}`];
        }
    });
    return next;
}

/**
 * Resolves item count and descriptive plural noun label for the active directory tab.
 *
 * @param {string} currentTab - Active directory tab ('place', 'job', or 'family').
 * @param {Array<object>} placeGroups - Computed place groupings.
 * @param {Array<object>} jobGroups - Computed career groupings.
 * @param {Array<object>} familyGroups - Computed family branch groupings.
 * @returns {{ currentTotalCount: number, countLabel: string }} Current count and label.
 *
 * @example
 *   getDirectoryTabStats('place', [{ id: 1 }], [], []);
 *   // returns { currentTotalCount: 1, countLabel: 'places' }
 *
 * @example
 *   getDirectoryTabStats('job', [], [{ id: 'Engineer' }, { id: 'Doctor' }], []);
 *   // returns { currentTotalCount: 2, countLabel: 'careers' }
 */
function getDirectoryTabStats(currentTab, placeGroups, jobGroups, familyGroups) {
    const currentTotalCount = currentTab === 'place' ? placeGroups.length : (currentTab === 'job' ? jobGroups.length : familyGroups.length);
    const countLabel = currentTab === 'place' ? 'places' : (currentTab === 'job' ? 'careers' : 'families');
    return { currentTotalCount, countLabel };
}

/**
 * Creates dispatch callbacks for selecting places, regions, jobs, and family names in the quick directory.
 *
 * @param {object} options - Options object.
 * @param {Function} options.onFilterBy - Primary filter dispatch callback.
 * @param {Function} [options.onFlyToLocation] - Optional callback to pan/fly map to a specific location.
 * @param {Function} [options.onFlyToRegion] - Optional callback to pan/fly map to a bounding region.
 * @returns {{
 *   handleSelectLocation: Function,
 *   handleSelectRegion: Function,
 *   handleSelectJob: Function,
 *   handleSelectFamily: Function
 * }} Collection of category selection handlers.
 *
 * @example
 *   const handlers = createDirectorySelectionHandlers({
 *     onFilterBy: (type, val) => console.log(type, val),
 *     onFlyToLocation: (loc) => map.flyTo(loc)
 *   });
 *   handlers.handleSelectLocation('Kerala, India');
 *
 * @example
 *   const handlers = createDirectorySelectionHandlers({
 *     onFilterBy: () => {}
 *   });
 *   handlers.handleSelectJob('Physician');
 */
function createDirectorySelectionHandlers({ onFilterBy, onFlyToLocation, onFlyToRegion }) {
    const handleSelectLocation = (place) => {
        const cleanPlace = cleanLocationDisplayName(place);
        onFilterBy('place', cleanPlace);
        if (onFlyToLocation) onFlyToLocation(place);
    };

    const handleSelectRegion = (regionName, regionPlaces) => {
        onFilterBy('place', regionName);
        if (onFlyToRegion) onFlyToRegion(regionName, regionPlaces);
    };

    const handleSelectJob = (job) => {
        onFilterBy('job', job);
    };

    const handleSelectFamily = (family) => {
        onFilterBy('family', family);
    };

    return {
        handleSelectLocation,
        handleSelectRegion,
        handleSelectJob,
        handleSelectFamily
    };
}

/**
 * Hook computing grouped directory collections (places hierarchy, jobs, and family branches)
 * filtered by the current directory tab and search query string.
 *
 * @param {object} params
 * @param {FamilyTree} params.tree - Family tree domain model
 * @param {string} params.currentTab - Active directory tab ('place' | 'job' | 'family')
 * @param {string} params.searchQuery - User-entered search filter query
 * @returns {{
 *   placeGroups: Array<object>,
 *   locationHierarchyTree: Array<object>,
 *   jobGroups: Array<object>,
 *   familyGroups: Array<object>
 * }}
 *
 * @example
 * const { placeGroups, locationHierarchyTree } = useDirectoryGroupData({
 *   tree,
 *   currentTab: 'place',
 *   searchQuery: 'Kerala'
 * });
 *
 * @example
 * const { jobGroups, familyGroups } = useDirectoryGroupData({
 *   tree,
 *   currentTab: 'job',
 *   searchQuery: 'Engineer'
 * });
 */
function useDirectoryGroupData({ tree, currentTab, searchQuery }) {
    const placeGroups = useMemo(() => computePlaceGroups(tree), [tree]);

    const locationHierarchyTree = useMemo(() => {
        const q = (currentTab === 'place' ? searchQuery : '').toLowerCase().trim();
        return buildLocationHierarchy(placeGroups, q);
    }, [placeGroups, searchQuery, currentTab]);

    const jobGroups = useMemo(() => {
        const q = (currentTab === 'job' ? searchQuery : '').toLowerCase().trim();
        return computeJobGroups(tree, q);
    }, [tree, searchQuery, currentTab]);

    const familyGroups = useMemo(() => {
        const q = (currentTab === 'family' ? searchQuery : '').toLowerCase().trim();
        return computeFamilyGroups(tree, q);
    }, [tree, searchQuery, currentTab]);

    return { placeGroups, locationHierarchyTree, jobGroups, familyGroups };
}

/**
 * Hook to automatically scroll the currently active directory item into view after selection changes.
 *
 * @param {React.RefObject} activeItemRef - DOM ref to the active directory list element.
 * @param {Array<any>} dependencies - Array of trigger dependencies (place, job, family, tab).
 *
 * @example
 * const ref = { current: document.createElement('div') };
 * useDirectoryAutoScroll(ref, ['Kerala', 'place']);
 *
 * @example
 * useDirectoryAutoScroll({ current: null }, []);
 */
function useDirectoryAutoScroll(activeItemRef, dependencies) {
    useEffect(() => {
        if (activeItemRef.current) {
            const timer = setTimeout(() => {
                activeItemRef.current?.scrollIntoView({
                    behavior: 'smooth',
                    block: 'center'
                });
            }, 100);
            return () => clearTimeout(timer);
        }
    }, dependencies);
}

/**
 * Hook managing tree node collapse states in the directory selector and auto-scrolling
 * the active highlighted location, job, or family node into view.
 *
 * @param {object} params
 * @param {string|null} params.activePlaceName - Currently active place name
 * @param {string|null} params.activeJobName - Currently active job name
 * @param {string|null} params.activeFamilyName - Currently active family name
 * @param {string} params.currentTab - Active tab identifier
 * @param {Array<object>} params.placeGroups - Computed place groupings for uncollapsing paths
 * @returns {{
 *   collapsedNodes: object,
 *   activeItemRef: React.RefObject<HTMLElement>,
 *   toggleCollapse: (nodeKey: string, e?: React.SyntheticEvent) => void
 * }}
 *
 * @example
 * const { collapsedNodes, activeItemRef, toggleCollapse } = useDirectoryCollapseAndScroll({
 *   activePlaceName: 'Thrissur',
 *   activeJobName: null,
 *   activeFamilyName: null,
 *   currentTab: 'place',
 *   placeGroups: []
 * });
 * toggleCollapse('Asia/India');
 *
 * @example
 * const { activeItemRef } = useDirectoryCollapseAndScroll({
 *   activePlaceName: null,
 *   activeJobName: 'Doctor',
 *   activeFamilyName: null,
 *   currentTab: 'job',
 *   placeGroups: []
 * });
 */
function useDirectoryCollapseAndScroll({
    activePlaceName,
    activeJobName,
    activeFamilyName,
    currentTab,
    placeGroups
}) {
    const [collapsedNodes, setCollapsedNodes] = useState({});
    const activeItemRef = useRef(null);

    useEffect(() => {
        if (activePlaceName) {
            setCollapsedNodes(prev => uncollapseLocationHierarchy(prev, activePlaceName, placeGroups, isPlaceMatch));
        }
    }, [activePlaceName, placeGroups]);

    useDirectoryAutoScroll(activeItemRef, [activePlaceName, activeJobName, activeFamilyName, currentTab]);

    const toggleCollapse = (nodeKey, e) => {
        if (e) e.stopPropagation();
        setCollapsedNodes(prev => ({
            ...prev,
            [nodeKey]: !prev[nodeKey]
        }));
    };

    return { collapsedNodes, activeItemRef, toggleCollapse };
}

/**
 * Synchronizes and manages the active tab selection within the directory view.
 *
 * @param {object|null} activeFilter - Active tree filter specification.
 * @param {string} [initialTab='place'] - Default tab fallback.
 * @returns {[string, Function]} Current tab identifier and its setter function.
 *
 * @example
 *   const [tab, setTab] = useDirectoryTabState(null, 'job');
 *
 * @example
 *   const [tab, setTab] = useDirectoryTabState({ filterType: 'place', value: 'Kerala' }, 'place');
 */
function useDirectoryTabState(activeFilter, initialTab = 'place') {
    const [currentTab, setCurrentTab] = useState(() => resolveActiveDirectoryTab(activeFilter, initialTab));

    useEffect(() => {
        const resolved = resolveActiveDirectoryTab(activeFilter, null);
        if (resolved) {
            setCurrentTab(resolved);
        }
    }, [activeFilter?.filterType, activeFilter?.tab]);

    return [currentTab, setCurrentTab];
}

/**
 * Resolves active directory filter values for place, job, and family from an active filter state.
 *
 * @param {object|null} activeFilter - Active tree filter specification.
 * @returns {{ activePlaceName: string|null, activeJobName: string|null, activeFamilyName: string|null }}
 *   Resolved active names for directory tab categories.
 *
 * @example
 *   const { activePlaceName } = resolveActiveDirectoryFilterNames({ filterType: 'place', value: 'Paris' });
 *
 * @example
 *   const { activeJobName } = resolveActiveDirectoryFilterNames({ filterType: 'job', value: 'Architect' });
 */
function resolveActiveDirectoryFilterNames(activeFilter) {
    return {
        activePlaceName: activeFilter?.filterType === 'place' ? activeFilter.value : null,
        activeJobName: activeFilter?.filterType === 'job' ? activeFilter.value : null,
        activeFamilyName: activeFilter?.filterType === 'family' ? activeFilter.value : null
    };
}

/**
 * Hook managing directory tabs, location hierarchy tree computations, career/family groupings,
 * active item scrolling, and selection callbacks for QuickDirectorySelector.
 *
 * @param {object} options
 * @param {FamilyTree} options.tree - Genealogical family tree instance
 * @param {object|null} options.activeFilter - Currently active filter specification
 * @param {Function} options.onFilterBy - Callback to activate category or attribute filter
 * @param {Function} [options.onFlyToLocation] - Optional callback to fly map to specific place
 * @param {Function} [options.onFlyToRegion] - Optional callback to fly map to broad region
 * @param {string} [options.initialTab='place'] - Default directory tab identifier
 * @returns {{
 *   currentTab: string,
 *   setCurrentTab: Function,
 *   searchQuery: string,
 *   setSearchQuery: Function,
 *   collapsedNodes: object,
 *   locationHierarchyTree: Array<object>,
 *   jobGroups: Array<object>,
 *   familyGroups: Array<object>,
 *   activePlaceName: string|null,
 *   activeJobName: string|null,
 *   activeFamilyName: string|null,
 *   activeItemRef: React.RefObject,
 *   toggleCollapse: Function,
 *   handleSelectLocation: Function,
 *   handleSelectRegion: Function,
 *   handleSelectJob: Function,
 *   handleSelectFamily: Function,
 *   currentTotalCount: number,
 *   countLabel: string
 * }}
 *
 * @example
 *   const dir = useQuickDirectoryData({ tree, activeFilter: null, onFilterBy: () => {} });
 *
 * @example
 *   const dir = useQuickDirectoryData({
 *       tree,
 *       activeFilter: { filterType: 'job', value: 'Teacher' },
 *       onFilterBy: handleFilter,
 *       initialTab: 'job'
 *   });
 */
function useQuickDirectoryData({
    tree, activeFilter, onFilterBy, onFlyToLocation, onFlyToRegion, initialTab = 'place'
}) {
    const [currentTab, setCurrentTab] = useDirectoryTabState(activeFilter, initialTab);
    const [searchQuery, setSearchQuery] = useState('');

    const { placeGroups, locationHierarchyTree, jobGroups, familyGroups } =
        useDirectoryGroupData({ tree, currentTab, searchQuery });

    const { activePlaceName, activeJobName, activeFamilyName } = resolveActiveDirectoryFilterNames(activeFilter);

    const { collapsedNodes, activeItemRef, toggleCollapse } = useDirectoryCollapseAndScroll({
        activePlaceName, activeJobName, activeFamilyName, currentTab, placeGroups
    });

    const { handleSelectLocation, handleSelectRegion, handleSelectJob, handleSelectFamily } =
        createDirectorySelectionHandlers({ onFilterBy, onFlyToLocation, onFlyToRegion });

    const { currentTotalCount, countLabel } = getDirectoryTabStats(currentTab, placeGroups, jobGroups, familyGroups);

    return {
        currentTab, setCurrentTab, searchQuery, setSearchQuery,
        collapsedNodes, locationHierarchyTree, jobGroups, familyGroups,
        activePlaceName, activeJobName, activeFamilyName, activeItemRef,
        toggleCollapse, handleSelectLocation, handleSelectRegion,
        handleSelectJob, handleSelectFamily, currentTotalCount, countLabel
    };
}

