/**
 * Computes collapse, active state, all places, and child locations for a country hierarchy node.
 *
 * @param {Object} options
 * @param {Object} options.countryNode - Country node object with name, locations, and states.
 * @param {Object} options.collapsedNodes - Map of collapsed state by node key.
 * @param {string|null} options.activePlaceName - Active place name filter.
 * @param {Function} options.isPlaceMatch - Place matching predicate function.
 * @returns {{
 *   isCountryCollapsed: boolean,
 *   allCountryPlaces: Array<Object>,
 *   isCountryActive: boolean,
 *   childCountryLocations: Array<Object>,
 *   hasCountryStates: boolean,
 *   hasCountryChildLocations: boolean
 * }} Computed country node layout state.
 *
 * @example
 *   resolveCountryNodeState({
 *     countryNode: { name: 'India', locations: [], states: [] },
 *     collapsedNodes: {},
 *     activePlaceName: null,
 *     isPlaceMatch: () => false
 *   });
 *
 * @example
 *   resolveCountryNodeState({
 *     countryNode: { name: 'USA', locations: [{ place: 'New York' }], states: [] },
 *     collapsedNodes: { USA: true },
 *     activePlaceName: 'New York',
 *     isPlaceMatch: (a, b) => a === b
 *   });
 */
function resolveCountryNodeState({
    countryNode,
    collapsedNodes,
    activePlaceName,
    isPlaceMatch
}) {
    const isCountryCollapsed = !!collapsedNodes[countryNode.name];
    const allCountryPlaces = getAllCountryPlaces(countryNode);
    const isCountryActive = isDirectoryRegionActive(
        countryNode.name,
        allCountryPlaces,
        activePlaceName,
        isPlaceMatch,
        'country'
    );
    const childCountryLocations = filterDistinctChildLocations(countryNode.locations, countryNode.name);
    const hasCountryStates = countryNode.states.length > 0;
    const hasCountryChildLocations = childCountryLocations.length > 0;

    return {
        isCountryCollapsed,
        allCountryPlaces,
        isCountryActive,
        childCountryLocations,
        hasCountryStates,
        hasCountryChildLocations
    };
}

