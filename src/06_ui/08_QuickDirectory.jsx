/**
 * Injects the Leaflet CSS stylesheet into the document head if not already loaded.
 *
 * @example
 * ensureLeafletStyles();
 * // => Appends <link id="leaflet-css" ...> to document.head if missing
 *
 * @example
 * ensureLeafletStyles();
 * // => No-op if stylesheet already loaded
 */
const ensureLeafletStyles = () => {
    if (!document.getElementById('leaflet-css')) {
        const link = document.createElement('link');
        link.id = 'leaflet-css';
        link.rel = 'stylesheet';
        link.href = 'https://unpkg.com/leaflet@1.9.4/dist/leaflet.css';
        document.head.appendChild(link);
    }
};

/**
 * Generates inline HTML markup for a Leaflet custom location pin marker.
 *
 * @param {string} place - The location label to display on the marker pin
 * @param {number} count - The count of individuals associated with this location
 * @param {boolean} isSelected - Whether this marker represents the currently active filter
 * @returns {string} HTML string representing the styled marker bubble
 *
 * @example
 * _buildMapMarkerHtml('Kochi', 42, true)
 * // => '<div style="display:flex;align-items:center;...background:#e11d48...<span>📍 Kochi</span>...'
 *
 * @example
 * _buildMapMarkerHtml('Thrissur', 15, false)
 * // => '<div style="display:flex;align-items:center;...background:#2563eb...<span>📍 Thrissur</span>...'
 */
function _buildMapMarkerHtml(place, count, isSelected) {
    const bg = isSelected ? '#e11d48' : '#2563eb';
    const padding = isSelected ? '6px 12px' : '4px 9px';
    const shadow = isSelected
        ? '0 0 0 4px rgba(225,29,72,0.3), 0 6px 18px rgba(0,0,0,0.35)'
        : '0 4px 14px rgba(0,0,0,0.3)';
    return `
            <div style="display:flex;align-items:center;justify-content:center;background:${bg};color:white;border-radius:9999px;padding:${padding};font-size:11.5px;font-weight:bold;box-shadow:${shadow};border:2px solid white;white-space:nowrap;cursor:pointer;transform:translate(-50%, -50%);transition:all 0.2s ease;">
                <span>📍 ${place}</span>
                <span style="background:rgba(255,255,255,0.28);border-radius:9999px;padding:0.5px 5px;margin-left:4px;font-size:10px;">${count}</span>
            </div>
        `;
}

/**
 * Creates an HTML divIcon instance for a Leaflet geographical marker.
 *
 * @param {object} L - The global Leaflet namespace object.
 * @param {string} place - The location label to display on the marker pin.
 * @param {number} count - The count of individuals associated with this location.
 * @param {boolean} isSelected - Whether this marker represents the currently active filter.
 * @returns {object} Leaflet divIcon object configured with custom styling.
 *
 * @example
 * createMapMarkerIcon(L, 'Kochi', 42, true)
 * // => L.divIcon with rose background (#e11d48) and enlarged padding
 *
 * @example
 * createMapMarkerIcon(L, 'Thrissur', 15, false)
 * // => L.divIcon with blue background (#2563eb) and standard padding
 */
const createMapMarkerIcon = (L, place, count, isSelected) => {
    return L.divIcon({
        className: 'custom-map-marker',
        html: _buildMapMarkerHtml(place, count, isSelected),
        iconSize: [0, 0],
        iconAnchor: [0, 0]
    });
};

/**
 * Adjusts the map view to either focus on an active location marker or fit all bounds.
 *
 * @param {object} map - Leaflet map instance.
 * @param {Array<{place: string, coords: [number, number], marker: object}>} markers - Registered map markers.
 * @param {string|null} activePlaceName - Currently selected place name, if any.
 * @param {Array<[number, number]>} bounds - Coordinates representing all plotted markers.
 *
 * @example
 * adjustMapViewToBounds(map, [{ place: 'Kochi', coords: [9.93, 76.26] }], 'Kochi', [[9.93, 76.26]])
 * // => Focuses map on [9.93, 76.26] at specific location zoom level
 *
 * @example
 * adjustMapViewToBounds(map, markers, null, [[9.93, 76.26], [10.52, 76.21]])
 * // => Executes map.fitBounds with padding and maxZoom 12
 */
const adjustMapViewToBounds = (map, markers, activePlaceName, bounds) => {
    if (activePlaceName) {
        const target = (markers || []).find(m => m.place.toLowerCase().trim() === activePlaceName.toLowerCase().trim());
        if (target) {
            map.setView(target.coords, getZoomForLocation(activePlaceName));
            return;
        }
    }
    if (bounds && bounds.length > 0) {
        const maxZoom = activePlaceName ? getZoomForLocation(activePlaceName) : 12;
        map.fitBounds(bounds, { padding: [80, 80], maxZoom });
    }
};

/**
 * Instantiates and binds Leaflet markers for a list of grouped locations on the map.
 *
 * @param {Object} options
 * @param {Object} options.L - Global Leaflet namespace.
 * @param {Object} options.map - Leaflet map instance.
 * @param {Array<{ place: string, count: number }>} options.placeGroups - Grouped location statistics.
 * @param {string|null} options.activePlaceName - Currently focused place name, if any.
 * @param {Function} options.onFilterBy - Callback invoked when a marker pin is clicked.
 * @returns {{ markers: Array<{ place: string, coords: [number, number], marker: Object }>, bounds: Array<[number, number]> }} Created marker records and bounding coordinates.
 *
 * @example
 * const { markers, bounds } = createAndBindMapMarkers({
 *   L, map, placeGroups: [{ place: 'Thrissur', count: 12 }],
 *   activePlaceName: 'Thrissur', onFilterBy: (t, v) => {}
 * });
 *
 * @example
 * const { markers } = createAndBindMapMarkers({
 *   L, map, placeGroups: [], activePlaceName: null, onFilterBy: () => {}
 * });
 */
function createAndBindMapMarkers({ L, map, placeGroups, activePlaceName, onFilterBy }) {
    const markers = [];
    const bounds = [];

    for (const group of placeGroups) {
        const coords = resolveLocationCoords(group.place);
        if (coords) {
            bounds.push(coords);
            const isSelected = activePlaceName && activePlaceName.toLowerCase().trim() === group.place.toLowerCase().trim();
            const icon = createMapMarkerIcon(L, group.place, group.count, isSelected);
            const marker = L.marker(coords, { icon }).addTo(map);
            marker.on('click', () => {
                onFilterBy('place', group.place);
                map.flyTo(coords, getZoomForLocation(group.place), { duration: 0.8 });
            });
            markers.push({ place: group.place, coords, marker });
        }
    }
    return { markers, bounds };
}

/**
 * Refreshes custom HTML divIcons for existing markers to reflect selection states and counts.
 *
 * @param {Object} options
 * @param {Object} options.L - Global Leaflet namespace.
 * @param {Array<{ place: string, marker: Object }>} options.markers - Active marker entries.
 * @param {Array<{ place: string, count: number }>} options.placeGroups - Place counts.
 * @param {string|null} options.activePlaceName - Selected location name.
 *
 * @example
 * updateMarkerIcons({ L: window.L, markers, placeGroups, activePlaceName: 'Thrissur' });
 *
 * @example
 * updateMarkerIcons({ L: null, markers: [] });
 */
function updateMarkerIcons({ L, markers, placeGroups, activePlaceName }) {
    if (!L || !markers) return;
    markers.forEach(({ place, marker }) => {
        const isSelected = activePlaceName && activePlaceName.toLowerCase().trim() === place.toLowerCase().trim();
        const count = placeGroups.find(g => g.place === place)?.count || 0;
        marker.setIcon(createMapMarkerIcon(L, place, count, isSelected));
    });
}

/**
 * Smoothly navigates the Leaflet map to frame a geographical region or multiple place coordinates.
 *
 * @param {Object} options
 * @param {Object} options.L - Global Leaflet namespace.
 * @param {Object} options.map - Leaflet map instance.
 * @param {string} options.regionName - Geographical region name.
 * @param {Array<{ place: string }>} [options.regionPlaces] - Places belonging to the region.
 *
 * @example
 * flyMapToRegion({ L: window.L, map, regionName: 'Kerala', regionPlaces: [{ place: 'Kochi' }, { place: 'Thrissur' }] });
 *
 * @example
 * flyMapToRegion({ L: window.L, map, regionName: 'India', regionPlaces: [] });
 */
function flyMapToRegion({ L, map, regionName, regionPlaces }) {
    if (!map || !L) return;
    const zoom = getZoomForLocation(regionName);
    let coordsList = (regionPlaces || [])
        .map(p => resolveLocationCoords(p.place))
        .filter(Boolean);
    if (coordsList.length === 0) {
        const regionCoords = resolveLocationCoords(regionName);
        if (regionCoords) coordsList = [regionCoords];
    }
    if (coordsList.length === 1) {
        map.flyTo(coordsList[0], zoom, { duration: 0.8 });
    } else if (coordsList.length > 1) {
        const bounds = L.latLngBounds(coordsList);
        map.fitBounds(bounds, { padding: [60, 60], maxZoom: zoom });
    }
}

/**
 * Instantiates and configures a Leaflet map with standard tiles and bottom-right zoom control.
 *
 * @param {HTMLElement} container - DOM element container for the map.
 * @param {Object} L - Global Leaflet library instance.
 * @param {[number, number]} [center=[10.3071, 76.3333]] - Initial map center coordinate [lat, lng].
 * @param {number} [zoom=9] - Initial zoom level.
 * @returns {Object} Configured Leaflet map instance.
 *
 * @example
 * const map = setupLeafletMapInstance(containerRef.current, window.L);
 *
 * @example
 * const map = setupLeafletMapInstance(containerRef.current, window.L, [9.93, 76.26], 11);
 */
function setupLeafletMapInstance(container, L, center = [10.3071, 76.3333], zoom = 9) {
    const map = L.map(container, {
        zoomControl: false,
        attributionControl: false
    }).setView(center, zoom);

    L.control.zoom({ position: 'bottomright' }).addTo(map);

    L.tileLayer('https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png', {
        maxZoom: 19,
        attribution: '© OpenStreetMap'
    }).addTo(map);

    return map;
}

/**
 * Hook tracking the last selected map location and re-activating place filters
 * when the user re-opens the map view without an active filter.
 *
 * @param {object} params
 * @param {object|null} params.activeFilter - Active filter object ({ filterType, value })
 * @param {boolean} params.showMap - Whether the map view is currently displayed
 * @param {Function} params.onFilterBy - Filter activation callback
 * @returns {{
 *   activePlaceName: string|null,
 *   lastSelectedPlace: string|null
 * }}
 *
 * @example
 * const { activePlaceName } = useMapActivePlaceTracking({
 *   activeFilter: { filterType: 'place', value: 'Thrissur' },
 *   showMap: true,
 *   onFilterBy: () => {}
 * });
 *
 * @example
 * const { activePlaceName } = useMapActivePlaceTracking({
 *   activeFilter: null,
 *   showMap: false,
 *   onFilterBy: () => {}
 * });
 */
function useMapActivePlaceTracking({ activeFilter, showMap, onFilterBy }) {
    const [lastSelectedPlace, setLastSelectedPlace] = useState(null);

    // Track active place when explicitly set
    useEffect(() => {
        if (activeFilter?.filterType === 'place' && activeFilter.value) {
            setLastSelectedPlace(activeFilter.value);
        }
    }, [activeFilter]);

    // When returning to map view without an active filter, re-activate the last selected place if available
    const prevShowMapRef = useRef(showMap);
    useEffect(() => {
        if (!prevShowMapRef.current && showMap) {
            if (!activeFilter && lastSelectedPlace) {
                onFilterBy('place', lastSelectedPlace);
            }
        }
        prevShowMapRef.current = showMap;
    }, [showMap, activeFilter, lastSelectedPlace, onFilterBy]);

    const activePlaceName = activeFilter?.filterType === 'place' ? activeFilter.value : lastSelectedPlace;

    return { activePlaceName, lastSelectedPlace };
}

/**
 * Asynchronously loads Leaflet resources and instantiates the map instance with markers.
 *
 * @param {object} options
 * @param {React.MutableRefObject<object|null>} options.mapContainerRef - Ref to container DOM element
 * @param {React.MutableRefObject<object|null>} options.mapInstanceRef - Ref to active Leaflet Map
 * @param {React.MutableRefObject<Array<object>>} options.markersRef - Ref to active map markers array
 * @param {Array<object>} options.placeGroups - Groups of places with geolocation coordinates
 * @param {string|null} options.activePlaceName - Currently selected place name
 * @param {Function} options.onFilterBy - Filter callback when a marker is clicked
 * @param {() => boolean} options.isStillMounted - Checker returning whether the component is still mounted
 * @returns {Promise<void>}
 *
 * @example
 * await performLeafletInitialization({
 *   mapContainerRef: { current: null },
 *   mapInstanceRef: { current: null },
 *   markersRef: { current: [] },
 *   placeGroups: [],
 *   activePlaceName: null,
 *   onFilterBy: () => {},
 *   isStillMounted: () => false
 * });
 *
 * @example
 * await performLeafletInitialization({
 *   mapContainerRef: { current: document.createElement('div') },
 *   mapInstanceRef: { current: null },
 *   markersRef: { current: [] },
 *   placeGroups: [{ place: 'Kochi', count: 1 }],
 *   activePlaceName: 'Kochi',
 *   onFilterBy: () => {},
 *   isStillMounted: () => true
 * });
 */
async function performLeafletInitialization({
    mapContainerRef, mapInstanceRef, markersRef,
    placeGroups, activePlaceName, onFilterBy, isStillMounted
}) {
    if (mapInstanceRef.current) return;
    try {
        ensureLeafletStyles();
        await ScriptLoader.load('https://unpkg.com/leaflet@1.9.4/dist/leaflet.js');

        if (!isStillMounted() || !mapContainerRef.current || !window.L || mapInstanceRef.current) return;

        const L = window.L;
        const map = setupLeafletMapInstance(mapContainerRef.current, L);
        mapInstanceRef.current = map;
        const { markers, bounds } = createAndBindMapMarkers({
            L, map, placeGroups, activePlaceName, onFilterBy
        });
        markersRef.current = markers;

        adjustMapViewToBounds(map, markersRef.current, activePlaceName, bounds);
    } catch (err) {
        console.error("Map initialization failed:", err);
    }
}

/**
 * Hook asynchronously loading the Leaflet library and CSS stylesheet, creating the map
 * instance, plotting geographic markers for place groups, and fitting initial bounds.
 *
 * @param {object} params
 * @param {boolean} params.showMap - Whether map view is open
 * @param {Array<object>} params.placeGroups - Aggregated place groups with coordinates
 * @param {string|null} params.activePlaceName - Highlighted place name
 * @param {Function} params.onFilterBy - Marker click selection callback
 * @param {React.RefObject<HTMLElement>} params.mapContainerRef - Ref to map container div
 * @param {React.MutableRefObject<object|null>} params.mapInstanceRef - Ref holding Leaflet Map
 * @param {React.MutableRefObject<Array<object>>} params.markersRef - Ref holding plotted markers
 *
 * @example
 * useLeafletMapInitializer({
 *   showMap: true,
 *   placeGroups: [],
 *   activePlaceName: 'Kochi',
 *   onFilterBy: () => {},
 *   mapContainerRef: { current: null },
 *   mapInstanceRef: { current: null },
 *   markersRef: { current: [] }
 * });
 *
 * @example
 * useLeafletMapInitializer({
 *   showMap: false,
 *   placeGroups: [],
 *   activePlaceName: null,
 *   onFilterBy: () => {},
 *   mapContainerRef: { current: null },
 *   mapInstanceRef: { current: null },
 *   markersRef: { current: [] }
 * });
 */
function useLeafletMapInitializer({
    showMap, placeGroups, activePlaceName, onFilterBy,
    mapContainerRef, mapInstanceRef, markersRef
}) {
    useEffect(() => {
        let isMounted = true;
        if (!showMap && !mapInstanceRef.current) return;

        const timer = setTimeout(() => {
            performLeafletInitialization({
                mapContainerRef, mapInstanceRef, markersRef,
                placeGroups, activePlaceName, onFilterBy,
                isStillMounted: () => isMounted
            });
        }, 50);

        return () => {
            isMounted = false;
            clearTimeout(timer);
        };
    }, [showMap, placeGroups, activePlaceName, onFilterBy, mapContainerRef, mapInstanceRef, markersRef]);
}

/**
 * Hook synchronizing marker icons with current selection, panning/flying to active place,
 * and invalidating map container size on layout or sidebar width transitions.
 *
 * @param {object} params
 * @param {React.MutableRefObject<object|null>} params.mapInstanceRef - Ref to Leaflet Map instance
 * @param {React.MutableRefObject<Array<object>>} params.markersRef - Ref to plotted markers
 * @param {Array<object>} params.placeGroups - Aggregated place groups
 * @param {string|null} params.activePlaceName - Highlighted place name
 * @param {boolean} params.showMap - Whether map is visible
 * @param {number} params.sidebarWidth - Width of details sidebar
 * @param {boolean} params.isSidebarVisible - Whether sidebar is shown
 *
 * @example
 * useLeafletMarkerSync({
 *   mapInstanceRef: { current: null },
 *   markersRef: { current: [] },
 *   placeGroups: [],
 *   activePlaceName: 'Thrissur',
 *   showMap: true,
 *   sidebarWidth: 360,
 *   isSidebarVisible: false
 * });
 *
 * @example
 * useLeafletMarkerSync({
 *   mapInstanceRef: { current: null },
 *   markersRef: { current: [] },
 *   placeGroups: [],
 *   activePlaceName: null,
 *   showMap: false,
 *   sidebarWidth: 360,
 *   isSidebarVisible: true
 * });
 */
function useLeafletMarkerSync({
    mapInstanceRef, markersRef, placeGroups,
    activePlaceName, showMap, sidebarWidth, isSidebarVisible
}) {
    useEffect(() => {
        if (!mapInstanceRef.current || !window.L) return;
        updateMarkerIcons({ L: window.L, markers: markersRef.current, placeGroups, activePlaceName });
        if (activePlaceName && showMap) {
            flyMapToPlace(mapInstanceRef.current, markersRef.current, activePlaceName);
        }
    }, [activePlaceName, placeGroups, showMap, mapInstanceRef, markersRef]);

    useEffect(() => {
        if (mapInstanceRef.current && showMap) {
            const timer = setTimeout(() => {
                mapInstanceRef.current?.invalidateSize();
            }, 60);
            return () => clearTimeout(timer);
        }
    }, [showMap, sidebarWidth, isSidebarVisible, mapInstanceRef]);
}

/**
 * Custom hook to initialize and manage Leaflet map instance lifecycle,
 * geographic marker synchronization, flyTo panning, and container resize invalidation.
 *
 * @param {Object} options
 * @param {FamilyTree} options.tree - Family tree dataset
 * @param {Object|null} options.activeFilter - Current active filter { filterType, value }
 * @param {Function} options.onFilterBy - Callback invoked when clicking on a marker
 * @param {boolean} options.showMap - Whether the map view is currently visible
 * @param {number} options.sidebarWidth - Width of the collapsible sidebar in pixels
 * @param {boolean} options.isSidebarVisible - Whether any sidebar is visible
 * @returns {{
 *   mapContainerRef: React.RefObject<HTMLDivElement>,
 *   mapInstanceRef: React.MutableRefObject<Object>,
 *   markersRef: React.MutableRefObject<Array>,
 *   activePlaceName: string|null,
 *   placeGroups: Map
 * }}
 *
 * @example
 * const { mapContainerRef } = useLeafletMap({
 *   tree,
 *   activeFilter,
 *   onFilterBy,
 *   showMap,
 *   sidebarWidth,
 *   isSidebarVisible
 * });
 *
 * @example
 * // Bind container ref to Leaflet map mount DOM element
 * <div ref={mapContainerRef} className="absolute inset-0 z-0 w-full h-full" />
 */
function useLeafletMap({ tree, activeFilter, onFilterBy, showMap, sidebarWidth, isSidebarVisible }) {
    const mapContainerRef = useRef(null);
    const mapInstanceRef = useRef(null);
    const markersRef = useRef([]);

    const { activePlaceName } = useMapActivePlaceTracking({ activeFilter, showMap, onFilterBy });
    const placeGroups = useMemo(() => computePlaceGroups(tree), [tree]);

    useLeafletMapInitializer({
        showMap, placeGroups, activePlaceName, onFilterBy,
        mapContainerRef, mapInstanceRef, markersRef
    });

    useLeafletMarkerSync({
        mapInstanceRef, markersRef, placeGroups, activePlaceName,
        showMap, sidebarWidth, isSidebarVisible
    });

    return { mapContainerRef, mapInstanceRef, markersRef, activePlaceName, placeGroups };
}